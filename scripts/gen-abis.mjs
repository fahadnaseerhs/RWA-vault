#!/usr/bin/env node
/**
 * Typed ABIs from the Foundry build (T6 spec §4.3): `pnpm abis:gen` writes
 * packages/types/src/abis/<Contract>.ts from contracts/out/<Contract>.sol/<Contract>.json;
 * `pnpm abis:check` fails if the committed files differ from a fresh build, so a contract
 * change surfaces as a diff and a TypeScript error instead of a silent mis-encoding.
 * Run `forge build` first.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { format, resolveConfig } from "prettier";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = resolve(ROOT, "packages/types/src/abis");

/** The contracts DeployM3 deploys and the consoles talk to. */
export const CONTRACTS = [
  "ClaimTopicsRegistry",
  "TrustedIssuersRegistry",
  "IdentityRegistryStorage",
  "IdentityRegistry",
  "AssetRegistry",
  "CustodianAttestationSource",
  "ModularCompliance",
  "AssetLiveModule",
  "Token",
];

const constName = (c) => `${c[0].toLowerCase()}${c.slice(1)}Abi`;

async function render(name, body) {
  const filepath = resolve(OUT, `${name}.ts`);
  return format(body, { ...(await resolveConfig(filepath)), parser: "typescript", filepath });
}

async function generate() {
  const files = {};
  for (const c of CONTRACTS) {
    const artifact = resolve(ROOT, "contracts/out", `${c}.sol`, `${c}.json`);
    if (!existsSync(artifact))
      throw new Error(`${artifact} is missing; run \`forge build\` in contracts/`);
    const { abi } = JSON.parse(readFileSync(artifact, "utf8"));
    files[c] = await render(
      c,
      `// Generated by scripts/gen-abis.mjs from contracts/out/${c}.sol/${c}.json. Do not edit.\n` +
        `export const ${constName(c)} = ${JSON.stringify(abi)} as const;\n`,
    );
  }
  files.index = await render(
    "index",
    "// Generated by scripts/gen-abis.mjs. Do not edit.\n" +
      CONTRACTS.map((c) => `export { ${constName(c)} } from "./${c}.js";`).join("\n") +
      "\n",
  );
  return files;
}

const files = await generate();
if (process.argv.includes("--check")) {
  const stale = Object.entries(files).filter(([n, text]) => {
    const p = resolve(OUT, `${n}.ts`);
    return !existsSync(p) || readFileSync(p, "utf8") !== text;
  });
  if (stale.length) {
    console.error(`ABIs out of date: ${stale.map(([n]) => n).join(", ")}. Run \`pnpm abis:gen\`.`);
    process.exit(1);
  }
  console.log(`ABIs up to date (${CONTRACTS.length} contracts).`);
} else {
  mkdirSync(OUT, { recursive: true });
  for (const [n, text] of Object.entries(files)) writeFileSync(resolve(OUT, `${n}.ts`), text);
  console.log(`wrote ${Object.keys(files).length} files to packages/types/src/abis/`);
}
